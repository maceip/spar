def emit_pytest_suite(findings: list[Finding], out_dir: Path, accounts: dict[str, str]) -> Path:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    names = {a: a for a in accounts}
    src = _HEADER.replace("%ACCOUNTS%", json.dumps(accounts, indent=4))
    # map account roles used in templates to real account names
    src += '\nACCOUNTS_NAME = {"attacker": "attacker", "victim": "victim"}\n'
    for f in findings:
        tpl = _TEMPLATES.get(f.technique)
        if tpl is None:
            continue
        attacker = f.evidence.get("attacker_account") or "alice"
        victim = f.evidence.get("victim_account") or "bob"
        block = (
            tpl.replace("%FID%", f.id.replace("-", "_"))
            .replace("%OBJECTIVE%", f.objective.replace('"', "'"))
            .replace("%WITNESS%", f.witness.replace('"', "'"))
        )
        # generated tests address accounts by role; map roles to tokens
        block = block.replace('account="attacker"', f'account="{attacker}"')
        block = block.replace('account="victim"', f'account="{victim}"')
        block = block.replace('"/users/attacker/outbox"', f'"/users/{attacker}/outbox"')
        block = block.replace('ACCOUNTS_NAME["attacker"]', f'"{attacker}"')
        block = block.replace("%INVOICE%", json.dumps(f.evidence.get("invoice_id", "INV-0000")))
        block = block.replace("%AMOUNT%", json.dumps(f.evidence.get("amount", 0)))
        block = block.replace("%TRIGGER%", json.dumps((f.evidence.get("victim_trigger") or "what is my account status?")))
        truth = (f.evidence.get("truth_sha256") or "")
        block = block.replace("%TRUTH_SHA%", json.dumps(truth))
        src += block
    path = out_dir / "test_attacks.py"
    path.write_text(src, encoding="utf-8")
    return path
